// Regenerates platform/shared/abi from the Hardhat artifacts in contracts/.
//   cd contracts && npx hardhat compile && cd ../platform/shared && node scripts/sync-abi.mjs
// Writes one JSON file per contract (plain ABI array) and abi/index.ts with `as const` copies,
// so viem infers function names, arguments and return types.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const shared = join(here, "..");
const artifacts = join(shared, "..", "..", "contracts", "artifacts");

const SOURCES = [
  { name: "CojamPredict", file: "contracts/platform/CojamPredict.sol/CojamPredict.json", constName: "cojamPredictAbi" },
  { name: "CojamStaking", file: "contracts/platform/CojamStaking.sol/CojamStaking.json", constName: "cojamStakingAbi" },
  { name: "PredictLogic", file: "contracts/platform/PredictLogic.sol/PredictLogic.json", constName: "predictLogicAbi" },
  { name: "ERC20", file: "@openzeppelin/contracts/token/ERC20/ERC20.sol/ERC20.json", constName: "erc20Abi" },
];

let ts = "// Generated by scripts/sync-abi.mjs from contracts/artifacts. Do not edit by hand.\n\n";
for (const s of SOURCES) {
  const path = join(artifacts, s.file);
  if (!existsSync(path)) throw new Error(`missing artifact ${path}: run \`npx hardhat compile\` in contracts/`);
  const { abi } = JSON.parse(readFileSync(path, "utf8"));
  writeFileSync(join(shared, "abi", `${s.name}.json`), JSON.stringify(abi, null, 2) + "\n");
  ts += `export const ${s.constName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  console.log(`abi/${s.name}.json: ${abi.length} entries`);
}
writeFileSync(join(shared, "abi", "index.ts"), ts);
console.log("abi/index.ts written");
