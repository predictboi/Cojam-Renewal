// Self hosted fonts for the "Daily Paper" look (no runtime request to Google Fonts or a CDN).
// Reads the @font-face rules of the font packages and writes src/styles/fonts/*.css with woff2 sources only,
// pointing into node_modules, so Vite emits each subset as a hashed asset next to the app.
//   base.css  Besley (display, Latin and figures) and Pretendard Variable (text): every language, in the main CSS
//   ko.css    Hahmlet (Korean display), loaded when the language is Korean
//   ja.css    Shippori Antique B1 (Japanese display) and Pretendard JP Variable (Japanese text), loaded for Japanese
// The unicode-range of every subset stays, so a browser downloads only the subsets a page uses.
// Font files are not precached by the service worker; a CacheFirst runtime route keeps them after first use.
// Run: npm run fonts
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const NM = new URL('../node_modules/', import.meta.url);
const OUT = new URL('../src/styles/fonts/', import.meta.url);
const REL = '../../../node_modules/';

function faces(pkgCss, rename) {
  const css = readFileSync(new URL(pkgCss, NM), 'utf8');
  const dir = pkgCss.slice(0, pkgCss.lastIndexOf('/') + 1);
  const out = [];
  for (const m of css.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
    let body = m[1];
    const fam = /font-family:\s*['"]?([^;'"]+)['"]?;/.exec(body)[1];
    const woff2 = /url\(([^)]+?\.woff2)\)\s*format\(['"]?(woff2(?:-variations)?)['"]?\)/.exec(body);
    if (!woff2) continue;
    const url = REL + dir + woff2[1].replace(/^\.\//, '');
    const get = (p) => { const r = new RegExp(p + ':\\s*([^;]+);').exec(body); return r ? r[1].trim() : ''; };
    out.push('@font-face{font-family:"' + (rename[fam] || fam) + '";font-style:' + (get('font-style') || 'normal') + ';font-display:swap;font-weight:' + get('font-weight') +
      ';src:url(' + url + ') format("' + woff2[2] + '")' + (get('unicode-range') ? ';unicode-range:' + get('unicode-range') : '') + '}');
  }
  return out;
}

const R = { 'Besley Variable': 'Besley', 'Hahmlet Variable': 'Hahmlet' };
const head = (what) => '/* Generated by scripts/gen-fonts.mjs: ' + what + '. SIL Open Font License 1.1 (see each package). Do not edit. */\n';
const sets = {
  'base.css': ['Besley and Pretendard Variable', ['@fontsource-variable/besley/index.css', 'pretendard/dist/web/variable/pretendardvariable-dynamic-subset.css']],
  'ko.css': ['Hahmlet', ['@fontsource-variable/hahmlet/index.css']],
  'ja.css': ['Shippori Antique B1 and Pretendard JP Variable', ['@fontsource/shippori-antique-b1/400.css', 'pretendard-jp/dist/web/variable/pretendardvariable-jp-dynamic-subset.css']],
};
mkdirSync(OUT, { recursive: true });
for (const [file, [what, list]] of Object.entries(sets)) {
  const rules = list.flatMap((p) => faces(p, R));
  writeFileSync(new URL(file, OUT), head(what) + rules.join('\n') + '\n');
  console.log(file, rules.length, 'faces');
}
